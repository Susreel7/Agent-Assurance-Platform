"""Regulation-to-obligation gap analysis — template mapping only, no NLP."""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Any, Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field

from app.domains.assurance.probe_oracle import match_obligation_template


class SuggestedObligation(BaseModel):
    model_config = ConfigDict(extra="forbid")

    id: str = Field(max_length=128)
    template_ref: str = Field(max_length=128)
    category: str = Field(max_length=64)
    polarity: str = Field(max_length=32)
    statement: str = Field(max_length=512)
    strength: str = Field(default="binding", max_length=32)
    remediation_hint: str | None = Field(default=None, max_length=512)


class RuleGap(BaseModel):
    model_config = ConfigDict(extra="forbid")

    template_id: str
    control_ref: str
    framework_slug: str
    required_statement: str
    status: Literal["covered", "partial", "missing", "conflict"]
    matching_obligation_ids: list[str]
    suggested_obligation: SuggestedObligation | None = None


class RuleGapReport(BaseModel):
    model_config = ConfigDict(extra="forbid")

    agent_id: UUID
    agent_version_id: UUID
    frameworks: list[str]
    gaps: list[RuleGap]
    covered_count: int
    generated_at: datetime
    content_digest: str


_REMEDIATION_HINTS: dict[str, str] = {
    "RES-001-forbid-cross-border": (
        "Inject a policy reminder at session start — literature shows large violation "
        "reductions without retraining."
    ),
    "TOOL-001-allowlist": "Declare an explicit tool allowlist obligation bound to runtime checks.",
    "LOG-001-retention": "Add a retention-window obligation matching the engagement terms.",
    "HITL-001-write-approval": "Require human approval before mutating capabilities.",
}


def build_rule_gap_report(
    *,
    agent_id: UUID,
    agent_version_id: UUID,
    framework_slugs: list[str],
    required_rows: list[dict[str, Any]],
    obligations: list[dict[str, Any]],
) -> RuleGapReport:
    gaps: list[RuleGap] = []
    covered = 0
    for row in required_rows:
        template_id = str(row["template_id"])
        status, matching = match_obligation_template(
            template_id,
            str(row["required_statement"]),
            row.get("required_polarity"),
            obligations,
        )
        if status == "covered":
            covered += 1
        suggestion: SuggestedObligation | None = None
        if status in ("missing", "partial", "conflict"):
            suggestion = SuggestedObligation(
                id=f"{template_id}-suggested",
                template_ref=template_id,
                category=str(row.get("category") or "governance"),
                polarity=str(row.get("required_polarity") or "require"),
                statement=str(row["required_statement"])[:512],
                remediation_hint=_REMEDIATION_HINTS.get(template_id),
            )
        gaps.append(
            RuleGap(
                template_id=template_id,
                control_ref=str(row["control_ref"]),
                framework_slug=str(row["framework_slug"]),
                required_statement=str(row["required_statement"]),
                status=status,
                matching_obligation_ids=matching,
                suggested_obligation=suggestion,
            )
        )
    digest_payload = "|".join(
        sorted(f"{g.template_id}:{g.status}" for g in gaps),
    )
    from hashlib import sha256

    content_digest = "sha256:" + sha256(digest_payload.encode()).hexdigest()
    return RuleGapReport(
        agent_id=agent_id,
        agent_version_id=agent_version_id,
        frameworks=framework_slugs,
        gaps=gaps,
        covered_count=covered,
        generated_at=datetime.now(tz=UTC),
        content_digest=content_digest,
    )


def export_rule_gaps_markdown(report: RuleGapReport) -> str:
    lines = [
        "# Rule obligation gap report",
        "",
        f"Agent `{report.agent_id}` · version `{report.agent_version_id}`",
        f"Frameworks: {', '.join(report.frameworks) or '—'}",
        f"Covered templates: {report.covered_count} / {len(report.gaps)}",
        "",
        "| Control | Template | Status | Required statement |",
        "| --- | --- | --- | --- |",
    ]
    for gap in report.gaps:
        lines.append(
            f"| {gap.control_ref} | {gap.template_id} | {gap.status} | "
            f"{gap.required_statement[:120]} |"
        )
    lines.append("")
    lines.append("_Generated by deterministic template mapping — not legal advice._")
    return "\n".join(lines)
